WHERE member_category = 'guest' AND is_selectable = false;

ALTER TABLE public.players ENABLE TRIGGER players_normalize_category;

-- Consulta administrativa independente das politicas de leitura aninhadas.
CREATE OR REPLACE FUNCTION public.list_manageable_accounts()
RETURNS TABLE (
  user_id UUID,
  role TEXT,
  created_at TIMESTAMPTZ,
  player_id UUID,
  player_name TEXT,
  player_nickname TEXT,
  player_avatar_url TEXT
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_app_admin() THEN
    RAISE EXCEPTION 'Somente administradores podem consultar acessos.';
  END IF;

  RETURN QUERY
  SELECT
    profile.user_id,
    profile.role,
    profile.created_at,
    player.id,
    player.name,
    player.nickname,
    player.avatar_url
  FROM public.account_profiles profile
  LEFT JOIN public.players player ON player.id = profile.player_id
  ORDER BY
    CASE WHEN profile.role = 'admin' THEN 0 ELSE 1 END,
    lower(COALESCE(player.name, profile.user_id::TEXT));
END;
$$;

REVOKE ALL ON FUNCTION public.list_manageable_accounts() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.list_manageable_accounts() TO authenticated;

