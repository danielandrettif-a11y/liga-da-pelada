CREATE TABLE IF NOT EXISTS player_registration_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id UUID REFERENCES players(id) ON DELETE SET NULL,
  player_name TEXT NOT NULL,
  avatar_url TEXT,
  member_category TEXT NOT NULL,
  source TEXT NOT NULL CHECK (source IN ('legacy', 'site_signup', 'admin')),
  created_by_user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS player_registration_events_created_idx
ON player_registration_events (created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS admin_roster_reads (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO player_registration_events (
  player_id, player_name, avatar_url, member_category, source, created_by_user_id, created_at
)
SELECT player.id, player.name, player.avatar_url, player.member_category, 'legacy', NULL, player.created_at
FROM players AS player
WHERE NOT EXISTS (
  SELECT 1 FROM player_registration_events AS event WHERE event.player_id = player.id
);

INSERT INTO admin_roster_reads (user_id, last_seen_at)
SELECT user_id, now()
FROM account_profiles
WHERE role = 'admin'
ON CONFLICT (user_id) DO NOTHING;

CREATE OR REPLACE FUNCTION record_player_registration()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO player_registration_events (
    player_id, player_name, avatar_url, member_category, source, created_by_user_id, created_at
  ) VALUES (
    NEW.id, NEW.name, NEW.avatar_url, NEW.member_category,
    NEW.registration_source, NEW.created_by_user_id, NEW.created_at
  );
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS players_record_registration ON players;
CREATE TRIGGER players_record_registration
