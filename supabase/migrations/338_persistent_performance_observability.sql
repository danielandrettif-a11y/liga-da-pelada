-- Telemetria enxuta e sem dados pessoais para acompanhar p50/p95 reais.
BEGIN;

CREATE TABLE IF NOT EXISTS public.app_performance_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('server_error', 'client_error', 'web_vital', 'client_action', 'match_step')),
  name text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 100),
  path text,
  value numeric,
  rating text,
  success boolean,
  message text,
  digest text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  recorded_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS app_performance_events_recent_idx
  ON public.app_performance_events (recorded_at DESC);
CREATE INDEX IF NOT EXISTS app_performance_events_metric_idx
  ON public.app_performance_events (kind, name, recorded_at DESC)
  WHERE value IS NOT NULL;

ALTER TABLE public.app_performance_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.app_performance_events FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, DELETE ON public.app_performance_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.app_performance_events_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.prune_app_performance_events()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF random() < 0.01 THEN
    DELETE FROM public.app_performance_events
    WHERE recorded_at < now() - interval '30 days';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS app_performance_events_retention ON public.app_performance_events;
CREATE TRIGGER app_performance_events_retention
AFTER INSERT ON public.app_performance_events
FOR EACH ROW EXECUTE FUNCTION public.prune_app_performance_events();

REVOKE ALL ON FUNCTION public.prune_app_performance_events() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.get_app_performance_summary(p_hours integer DEFAULT 24)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  result jsonb;
BEGIN
  IF NOT public.is_app_admin() THEN
    RAISE EXCEPTION 'Acesso restrito ao administrador do aplicativo.';
  END IF;
  SELECT coalesce(jsonb_agg(to_jsonb(summary_row) ORDER BY summary_row.p95_ms DESC NULLS LAST), '[]'::jsonb)
  INTO result
  FROM (
    SELECT
      kind,
      name,
      coalesce(path, '') AS path,
      count(*)::integer AS samples,
      round(percentile_cont(0.50) WITHIN GROUP (ORDER BY value)::numeric, 2) AS p50_ms,
      round(percentile_cont(0.95) WITHIN GROUP (ORDER BY value)::numeric, 2) AS p95_ms,
      round(max(value), 2) AS max_ms,
      count(*) FILTER (WHERE success = false OR rating = 'poor')::integer AS poor_or_failed
    FROM public.app_performance_events
    WHERE recorded_at >= now() - make_interval(hours => greatest(1, least(coalesce(p_hours, 24), 720)))
      AND value IS NOT NULL
    GROUP BY kind, name, coalesce(path, '')
  ) summary_row;
  RETURN result;
END;
$$;

REVOKE ALL ON FUNCTION public.get_app_performance_summary(integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_app_performance_summary(integer) TO authenticated;

NOTIFY pgrst, 'reload schema';
COMMIT;
